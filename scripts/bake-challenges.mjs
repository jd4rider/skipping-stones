#!/usr/bin/env node
/*
 * Build the 100-challenge journey and write it to src/challenges/data.js.
 *
 * Every challenge is generated and then verified: the generator searches real
 * throws and stores the one that satisfies the objective along with the numbers
 * it produced. A challenge that cannot be proven does not get written.
 *
 *   npm run bake
 */
import { writeFile } from 'node:fs/promises'
import { LOCATIONS, evaluateChallenge, generateChallenge, seedFor } from '../src/challenges/generator.js'
import { simulateThrow } from '../src/physics/simulation.js'

const PER_LOCATION = 20
const challenges = []
const problems = []

console.log(`Baking ${PER_LOCATION * LOCATIONS.length} challenges…`)
const started = Date.now()

LOCATIONS.forEach((location, locationIndex) => {
  for (let localIndex = 0; localIndex < PER_LOCATION; localIndex += 1) {
    const number = locationIndex * PER_LOCATION + localIndex + 1
    const seed = seedFor(`skipping-stones-${number}-${location.id}`)
    const challenge = generateChallenge({ number, locationIndex, localIndex, seed, dense: true })

    // Replay the stored proof through the same simulation the player gets.
    const world = { windX: challenge.windX, chop: challenge.chop, targets: challenge.targets }
    const replay = simulateThrow(challenge.proof.throw, world)
    const judged = evaluateChallenge(challenge, replay)
    if (!judged.passed) {
      problems.push(`${challenge.id}: proof does not satisfy its own objective (${judged.metric} < ${judged.target})`)
    }
    if (challenge.stars[2] < challenge.objective.target) {
      problems.push(`${challenge.id}: three-star threshold is below the pass mark`)
    }

    challenges.push(challenge)
  }
  const done = challenges.length
  console.log(`  ${location.name}: ${PER_LOCATION} challenges (${done} total)`)
})

const elapsed = ((Date.now() - started) / 1000).toFixed(1)
if (problems.length > 0) {
  console.error(`\n${problems.length} challenge(s) failed verification:`)
  for (const problem of problems) console.error(`  ${problem}`)
  process.exit(1)
}

const header = `// Generated by scripts/bake-challenges.mjs on ${new Date().toISOString()}.
// Do not edit by hand: run \`npm run bake\` so every challenge stays verified.
`
const body = `export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())}\n\nexport const CHALLENGES = ${JSON.stringify(challenges, null, 2)}\n`
await writeFile(new URL('../src/challenges/data.js', import.meta.url), `${header}${body}`)

const byType = challenges.reduce((totals, challenge) => {
  totals[challenge.objective.type] = (totals[challenge.objective.type] ?? 0) + 1
  return totals
}, {})
const stones = challenges.reduce((totals, challenge) => {
  totals[challenge.stoneId] = (totals[challenge.stoneId] ?? 0) + 1
  return totals
}, {})

console.log(`\nVerified ${challenges.length} challenges in ${elapsed}s.`)
console.log(`  objective mix: ${Object.entries(byType).map(([type, count]) => `${type} ${count}`).join(', ')}`)
console.log(`  stones: ${Object.entries(stones).map(([id, count]) => `${id} ${count}`).join(', ')}`)
console.log(`  skips required: ${Math.min(...challenges.filter((c) => c.objective.type === 'skips').map((c) => c.objective.target))}–${Math.max(...challenges.filter((c) => c.objective.type === 'skips').map((c) => c.objective.target))}`)
